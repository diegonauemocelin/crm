/** Função CRM_Tabela do Power Query (a mesma do contrato e do projeto do Power BI). */
export const M_CRM_TABELA = [
  '(nome as text, optional desde as nullable text) as table =>',
  'let',
  '    Pagina = (cursor as nullable text) as record =>',
  '        let',
  '            Filtro = if desde = null or desde = "" then [] else [desde = desde],',
  '            Consulta = if cursor = null then Filtro else Record.AddField(Filtro, "cursor", cursor),',
  '            Resposta = Web.Contents(',
  '                CRM_BaseUrl,',
  '                [',
  '                    RelativePath = nome,',
  '                    Query = Consulta,',
  '                    Headers = [#"X-BI-Key" = CRM_Chave, Accept = "application/json"],',
  '                    ManualStatusHandling = {400, 401, 404, 429},',
  '                    Timeout = #duration(0, 0, 10, 0)',
  '                ]',
  '            ),',
  '            Status = Value.Metadata(Resposta)[Response.Status],',
  '            Json = Json.Document(Resposta),',
  '            Ok = if Status = 200 then Json else error Error.Record("CRM", "Erro " & Text.From(Status) & " em " & nome, Json[message]?)',
  '        in',
  '            Ok,',
  '    Paginas = List.Generate(',
  '        () => Pagina(null),',
  '        each _ <> null,',
  '        each if _[next] = null then null else Pagina(_[next])',
  '    ),',
  '    Colunas = Paginas{0}[colunas],',
  '    Linhas = List.Combine(List.Transform(Paginas, each _[rows])),',
  '    Tabela = Table.FromRecords(Linhas, Colunas, MissingField.UseNull)',
  'in',
  '    Tabela',
].join('\n')

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function tableSection(t: BiTable): string[] {
  const out = [`### ${t.nome}`, '', t.descricao, '', `- **Grão:** ${t.grao}`, `- **Chave primária:** \`${t.chave}\` (única)`]
  if (t.janela) out.push(`- **Janela padrão:** ${t.janela}`)
  if (t.desde) out.push(`- **desde:** ${t.desde}`)
  if (t.tipo === 'dimensao') out.push('- **Leitura:** sempre completa (ignora `desde` e `meses`).')
  if (t.datas.length) out.push(`- **Datas para o calendário:** ${t.datas.map((d, i) => `\`${d}\`${i === 0 ? ' (ativa)' : ' (inativa)'}`).join(', ')}`)
  out.push('', '| Coluna | Tipo | Vazia? | Significado |', '|---|---|---|---|')
  for (const c of t.colunas) out.push(`| \`${c.nome}\` | ${c.tipo} | ${c.nulo ? 'pode' : 'não'} | ${cell(c.descricao)} |`)
  if (t.relacoes.length) {
    out.push('', 'Relações (muitos para um, filtro em direção única, da dimensão para esta tabela):', '')
    for (const r of t.relacoes) out.push(`- \`${t.nome}[${r.coluna}]\` → \`${r.tabela}[${r.chave}]\`${r.ativa === false ? ' (inativa: use USERELATIONSHIP)' : ''}`)
  }
  out.push('')
  return out
}

function typesSnippet(t: BiTable): string {
  const pairs = t.colunas.map((c) => `{"${c.nome}", ${M_TYPE[c.tipo]}}`)
  return `Table.TransformColumnTypes(${t.nome}_bruto, {${pairs.join(', ')}})`
}

